-- OpenG2P Catalog Extension DDL Script
-- Physical tables for Crop, Seed, Inputs, and Livestock Master Catalogs aligned with MDM

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pg_trgm";

-- ============================================================================
-- 0. CROP TAXONOMY & LOOKUP TABLES
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.crop_categories (
    category_id VARCHAR(50) PRIMARY KEY,
    category_code VARCHAR(50) UNIQUE NOT NULL,
    category_name VARCHAR(200) NOT NULL,
    description TEXT,
    status VARCHAR(50) DEFAULT 'ACTIVE',
    is_active BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE IF NOT EXISTS public.ecological_zones (
    zone_id VARCHAR(50) PRIMARY KEY,
    zone_code VARCHAR(50) UNIQUE NOT NULL,
    zone_name VARCHAR(200) NOT NULL,
    description TEXT,
    status VARCHAR(50) DEFAULT 'ACTIVE',
    is_active BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE IF NOT EXISTS public.crop_varieties (
    variety_id VARCHAR(100) PRIMARY KEY,
    variety_code VARCHAR(100) UNIQUE NOT NULL,
    variety_name VARCHAR(200) NOT NULL,
    crop_code VARCHAR(50),
    crop_name VARCHAR(200),
    scientific_name VARCHAR(200),
    breeder_source VARCHAR(200),
    release_year INTEGER,
    maturity_days INTEGER,
    potential_yield NUMERIC(10, 2),
    yield_unit VARCHAR(50),
    is_certified BOOLEAN DEFAULT TRUE,
    status VARCHAR(50) DEFAULT 'ACTIVE',
    is_active BOOLEAN DEFAULT TRUE NOT NULL
);

-- ============================================================================
-- 0B. LIVESTOCK TAXONOMY & LOOKUP TABLES
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.livestock_types (
    type_id VARCHAR(50) PRIMARY KEY,
    type_code VARCHAR(50) UNIQUE NOT NULL,
    type_name VARCHAR(200) NOT NULL,
    scientific_name VARCHAR(200),
    subfamily VARCHAR(100),
    description TEXT,
    ear_tag_range VARCHAR(100),
    species_type_code INTEGER,
    in_lis_population BOOLEAN DEFAULT TRUE,
    in_etlits_registry BOOLEAN DEFAULT TRUE,
    status VARCHAR(50) DEFAULT 'ACTIVE',
    is_active BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE IF NOT EXISTS public.livestock_breeds (
    breed_id VARCHAR(50) PRIMARY KEY,
    breed_code VARCHAR(50) UNIQUE NOT NULL,
    breed_name VARCHAR(200) NOT NULL,
    species_code VARCHAR(50),
    species_name VARCHAR(100),
    breed_type VARCHAR(50) DEFAULT 'Indigenous',
    abbreviation VARCHAR(20),
    primary_purpose VARCHAR(100),
    origin_country VARCHAR(100) DEFAULT 'Ethiopia',
    climate_adaptability VARCHAR(200),
    in_national_standard BOOLEAN DEFAULT TRUE,
    in_etlits_registry BOOLEAN DEFAULT FALSE,
    description TEXT,
    status VARCHAR(50) DEFAULT 'ACTIVE',
    is_active BOOLEAN DEFAULT TRUE NOT NULL
);

-- ============================================================================
-- 0C. SEED TAXONOMY & LOOKUP TABLES
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.seed_crops (
    crop_id VARCHAR(50) PRIMARY KEY,
    crop_code VARCHAR(50) UNIQUE NOT NULL,
    crop_name VARCHAR(200) NOT NULL,
    scientific_name VARCHAR(200),
    description TEXT,
    status VARCHAR(50) DEFAULT 'ACTIVE',
    is_active BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE IF NOT EXISTS public.seed_varieties (
    variety_id VARCHAR(100) PRIMARY KEY,
    variety_code VARCHAR(100) UNIQUE NOT NULL,
    variety_name VARCHAR(200) NOT NULL,
    seed_crop_code VARCHAR(50),
    seed_crop_name VARCHAR(200),
    breeder_source VARCHAR(200),
    release_year INTEGER,
    maturity_days INTEGER,
    potential_yield VARCHAR(100),
    yield_unit VARCHAR(50) DEFAULT 'Quintal/Ha',
    match_status VARCHAR(50) DEFAULT 'UNRESOLVED',
    description TEXT,
    is_certified BOOLEAN DEFAULT TRUE,
